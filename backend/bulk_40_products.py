print("🚀 Starting bulk upload of 40 products with Unsplash images...\n")

for item in products_list:
  img_url = item.pop("img_url")  # URL ko dict se alag kar rahe hain

  try:
    # 1. Unsplash se image download kar rahe hain
    img_response = requests.get(img_url)
    if img_response.status_code == 200:
      files = {"image": ("product.jpg", img_response.content, "image/jpeg")}

      # 2. API par POST request bhej rahe hain
      response = requests.post(API_URL, data=item, files=files)

      if response.status_code == 201:
        print(
            f"✅ Created: {item['name']} (Cat ID: {item['category']}) with"
            " image"
        )
      else:
        print(
            f"❌ Failed for {item['name']} | Status:"
            f" {response.status_code} | Error: {response.text}"
        )
    else:
      print(f"❌ Failed to download image for {item['name']}")
  except Exception as e:
    print(f"⚠️ Exception occurred for {item['name']}: {e}")

print("\n🎉 Bulk upload process completed!")